import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { adb, pause, find, tap, capture, output } from './android-ui.mjs';
const pkg = 'ie.ribbonpassport.universal';
await adb('shell', 'wm', 'size', '1600x2560');
await adb('shell', 'wm', 'density', '240');
await adb('shell', 'am', 'force-stop', pkg);
await adb('shell', 'am', 'start', '-n', `${pkg}/.MainActivity`);
await pause(1200);
await find('PC storage', 'up');
await find('Select Atlas Prime', 'up'); await capture('slice-two-07-tablet-pc');
await tap('Open full passport →'); await tap('Journey');
await find('Alert Ribbon'); await capture('slice-two-08-tablet-passport');
await adb('root'); await pause(800); await adb('wait-for-device');
const cache = '/data/user/0/ie.ribbonpassport.universal/cache';
const sourcePath = (await adb('shell', 'find', cache, '-name', 'RibbonPassport-App.json')).trim().split('\n')[0];
const source = JSON.parse(await adb('exec-out', 'cat', sourcePath));
const c = source.collection, p = c.pokemon.find(p => p.nickname === 'Atlas Prime');
assert.equal(p.earnedGames['alert-ribbon'], 'as'); assert.equal(p.shiny, true); assert.equal(p.source, 'manual');
assert.equal(p.currentlevel, 100); assert.equal(p.metLevel, 50);
assert.equal(c.appearance, 'automatic'); assert.equal(typeof c.updatedAt, 'number');
assert.equal(c.storage.boxes[1].slots[29], p.id); assert.equal(c.storage.boxes[1].wallpaper.sunMoon, 'sm09');
assert.equal(c.storage.boxes[1].wallpaper.design, 'classic'); assert.equal(c.storage.boxes[1].wallpaper.strength, 0.65);
await fs.writeFile(path.join(output, 'slice-two-tablet-result.json'), JSON.stringify({ at: new Date().toISOString(), platform: 'Android 36 x86_64 emulator', display: { width: 1600, height: 2560, density: 240 }, passed: ['same APK, tablet configuration', 'persisted second box and wallpaper', 'PC and quick preview', 'passport and earning history', 'native exported JSON includes required Swift fields, stable identity, exact slot and earning location'] }, null, 2));
console.log('Native tablet and exported backup checks passed.');
