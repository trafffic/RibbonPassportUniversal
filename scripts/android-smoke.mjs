import fs from 'node:fs/promises';
import path from 'node:path';
import { adb, pause, find, tap, capture, output, width, height } from './android-ui.mjs';
const serial = process.argv[3];
const pkg = 'ie.ribbonpassport.universal';
await adb('shell', 'am', 'force-stop', pkg);
await adb('shell', 'am', 'start', '-n', `${pkg}/.MainActivity`);
await pause(2000);
await find('PC storage'); await capture('01-collection');
await tap('Select Gardevoir');
await tap('Open full passport →');
await tap('Plan next ribbon');
await tap('Details for Alert Ribbon');
await tap('Alpha Sapphire');
await tap('Record Alert Ribbon');
await tap('Owned awards', 'up');
await tap('Details for Alert Ribbon');
await find('Earned in: Alpha Sapphire'); await capture('02-recorded');
await tap('Undo last change');
await tap('Plan next ribbon', 'up');
await tap('Details for Alert Ribbon');
await tap('Alpha Sapphire');
await tap('Record Alert Ribbon');
await tap('Journey', 'up');
await find('Alert Ribbon'); await capture('03-journey');
await adb('shell', 'svc', 'wifi', 'disable');
await adb('shell', 'svc', 'data', 'disable');
await adb('shell', 'am', 'force-stop', pkg);
await adb('shell', 'am', 'start', '-n', `${pkg}/.MainActivity`);
await pause(1500);
await tap('Open full passport →');
await tap('Journey');
await find('Alert Ribbon'); await capture('04-offline-relaunch');
await tap('Import / export', 'up');
await tap('Export collection');
await pause(800); await capture('05-native-export');
await adb('shell', 'input', 'keyevent', '4');
await fs.writeFile(path.join(output, 'result.json'), JSON.stringify({ platform: 'Android', serial, viewport: { width, height }, checks: ['PC selection', 'full passport', 'record ribbon with earning game', 'undo ribbon', 'Journey earning history', 'offline force-stop/relaunch restores SQLite collection', 'native export share sheet opened'], completedAt: new Date().toISOString() }, null, 2));
console.log('Android native smoke flow passed.');
