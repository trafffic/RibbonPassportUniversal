// Build-time only: prepare the original bundled iPhone artwork for crisp scaling.
// No sprite replacements or network downloads. Source artwork remains unchanged.
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import { PNG } from 'pngjs';
await fs.mkdir('assets/prepared', { recursive: true });
function prepare(bytes, factor) {
  const input = PNG.sync.read(bytes);
  let left = input.width, right = -1, top = input.height, bottom = -1;
  for (let y = 0; y < input.height; y++) for (let x = 0; x < input.width; x++) if (input.data[(y * input.width + x) * 4 + 3] > 8) {
    left = Math.min(left, x); right = Math.max(right, x); top = Math.min(top, y); bottom = Math.max(bottom, y);
  }
  if (right < left) throw new Error('Empty artwork');
  const output = new PNG({ width: (right - left + 1) * factor, height: (bottom - top + 1) * factor });
  for (let y = 0; y < output.height; y++) for (let x = 0; x < output.width; x++) {
    const from = ((Math.floor(y / factor) + top) * input.width + Math.floor(x / factor) + left) * 4;
    input.data.copy(output.data, (y * output.width + x) * 4, from, from + 4);
  }
  return PNG.sync.write(output);
}
const manifest = {}, provenance = [];
for (const file of await fs.readdir('assets/art')) {
  if (!file.endsWith('.png')) continue;
  const key = file.slice(0, -4);
  if (!/^(sprite-|game-|shiny-)/.test(key)) continue;
  const source = path.join('assets/art', file), bytes = await fs.readFile(source);
  const factor = key.startsWith('sprite-') ? 8 : 4;
  await fs.writeFile(path.join('assets/prepared', file), prepare(bytes, factor));
  manifest[key] = `../../assets/prepared/${file}`;
  if (key.startsWith('sprite-')) provenance.push({ key, source: source.replaceAll('\\', '/'), sha256: crypto.createHash('sha256').update(bytes).digest('hex'), scale: factor });
}
for (const file of await fs.readdir('assets/wallpapers')) {
  if (!/^sm-\d\d\.png$/.test(file)) continue;
  const key = `wallpaper-${file.slice(0, -4).replace('-', '')}`;
  await fs.writeFile(path.join('assets/prepared', key + '.png'), prepare(await fs.readFile(path.join('assets/wallpapers', file)), 8));
  manifest[key] = `../../assets/prepared/${key}.png`;
}
await fs.writeFile('src/ui/prepared-artwork.ts', `// Generated by scripts/prepare-artwork.mjs. Original reference artwork only.\nexport const preparedArtwork: Record<string, number> = {\n${Object.entries(manifest).sort().map(([key, file]) => `  ${JSON.stringify(key)}: require(${JSON.stringify(file)}),`).join('\n')}\n};\n`);
await fs.writeFile('assets/data/sprite-provenance.json', JSON.stringify({ source: 'Original bundled Ribbon Passport iPhone sprites', prepared: 'Alpha bounds > 8, nearest-neighbour 8x; all original visible pixels retained.', files: provenance }, null, 2));
console.log(`Prepared ${Object.keys(manifest).length} original artwork files; ${provenance.length} original Pokémon sprites.`);
