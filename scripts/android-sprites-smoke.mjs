// Local emulator only: restore the bundled sample through the actual file picker.
// The replaced emulator collection is archived by the normal import flow.
import fs from 'node:fs/promises';
import path from 'node:path';
import { adb, pause, find, tap, capture, output } from './android-ui.mjs';
const pkg = 'ie.ribbonpassport.universal';
await adb('push', path.resolve('assets/data/demo-backup.json'), '/sdcard/Download/original-sprite-samples.json');
await adb('shell', 'wm', 'size', 'reset');
await adb('shell', 'wm', 'density', 'reset');
await adb('shell', 'am', 'force-stop', pkg);
await adb('shell', 'am', 'start', '-n', `${pkg}/.MainActivity`);
await pause(1200);
await tap('Import / export', 'up');
await tap('Choose backup file');
await pause(700);
await tap('Show roots');
await tap('Downloads', 'down', true);
await tap('original-sprite-samples.json', 'down', true);
await find('6 Pokémon · 1 boxes');
await tap('Replace collection');
await find('Select Sparky', 'up');
await capture('original-sprites-phone-pc');
await tap('Select Gardevoir', 'up');
await find('Origin');
await capture('original-sprites-phone-preview');
await tap('Open full passport →');
await find('POKÉMON PASSPORT', 'up');
await capture('original-sprites-phone-passport');
await tap('Collection', 'up');
await adb('shell', 'wm', 'size', '1600x2560');
await adb('shell', 'wm', 'density', '240');
await adb('shell', 'am', 'force-stop', pkg);
await adb('shell', 'am', 'start', '-n', `${pkg}/.MainActivity`);
await pause(1200);
await find('Select Gardevoir', 'up');
await capture('original-sprites-tablet-pc');
await tap('Open full passport →');
await find('POKÉMON PASSPORT', 'up');
await capture('original-sprites-tablet-passport');
await fs.writeFile(path.join(output, 'original-sprites-result.json'), JSON.stringify({ at: new Date().toISOString(), platform: 'Android 36 x86_64 emulator', displays: ['1080×2400 / density 420', '1600×2560 / density 240'], passed: ['original bundled sample import through native picker', 'PC selection', 'quick preview', 'full passport', 'restored selected Pokémon after restart'], note: 'PNG captures require visual inspection for whole silhouettes and correct proportions.' }, null, 2));
console.log('Original sprite native captures complete.');
