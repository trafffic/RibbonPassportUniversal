import { test, expect } from '@playwright/test';
import { button, demo, options } from './helpers';

test('choose a species in dex order, then a form, and preserve it when editing', async ({ page }) => {
  await demo(page);
  await options(page, 'Add Pokémon');
  const species = page.getByRole('button', { name: /^Species:/ });
  const form = page.getByRole('button', { name: /^Form:/ });
  await expect(form).toHaveCount(0);
  await species.click();
  const choices = page.getByRole('button', { name: /^Choose #/ });
  await expect(choices.first()).toHaveAccessibleName('Choose #0001 Bulbasaur');
  await expect(choices.nth(24)).toHaveAccessibleName('Choose #0025 Pikachu');
  await expect(page.getByRole('button', { name: /^Choose #0000/ })).toHaveCount(0);
  await page.getByRole('textbox', { name: 'Search species', exact: true }).fill('pikachu');
  await expect(choices).toHaveCount(1);
  await button(page, 'Choose #0025 Pikachu').click();
  await expect(form).toHaveAccessibleName('Form: Standard');
  await form.click();
  await button(page, 'Choose Alola Cap').click();
  await expect(form).toHaveAccessibleName('Form: Alola Cap');
  await page.getByRole('textbox', { name: 'Nickname', exact: true }).fill('Cap partner');
  await button(page, 'Add to box').click();
  await expect(button(page, 'Select Cap partner')).toBeVisible();
  await page.reload();
  await expect(button(page, 'Select Cap partner')).toBeVisible();
  await button(page, 'Pokémon actions').click();
  await button(page, 'Edit Pokémon').click();
  await expect(species).toHaveAccessibleName('Species: #0025 Pikachu');
  await expect(form).toHaveAccessibleName('Form: Alola Cap');
  await species.click();
  await page.getByRole('textbox', { name: 'Search species', exact: true }).fill('caterpie');
  await button(page, 'Choose #0010 Caterpie').click();
  await expect(form).toHaveCount(0);
  await species.click();
  await page.getByRole('textbox', { name: 'Search species', exact: true }).fill('pikachu');
  await button(page, 'Choose #0025 Pikachu').click();
  await expect(form).toHaveAccessibleName('Form: Standard');
});
